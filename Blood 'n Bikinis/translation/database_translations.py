from pathlib import Path
from rubymarshal.reader import loads

def apply_by_source(section, names, descriptions=None):
    descriptions=descriptions or {}
    p=Path(__file__).resolve().parent/'extracted'/'Data'/f'{section}.rxdata'
    rows=loads(p.read_bytes())
    hits=set()
    for i,row in enumerate(rows):
        if row is None: continue
        a=row.attributes
        en=a.get('@name')
        en=en.decode('cp932','replace') if isinstance(en,bytes) else en
        desc=a.get('@description')
        desc=desc.decode('cp932','replace') if isinstance(desc,bytes) else desc
        name_zh=names.get(en)
        desc_zh=descriptions.get(desc)
        if name_zh is not None or desc_zh is not None:
            DATA.setdefault(section,{})[i]=(name_zh,desc_zh)
            if name_zh is not None: hits.add(('name',en))
            if desc_zh is not None: hits.add(('description',desc))
    expected={('name',x) for x in names}|{('description',x) for x in descriptions}
    missing=expected-hits
    if missing: raise ValueError(f'{section} unmatched: {missing}')

